// Generates lib/festivalDates.js: the date of every festival day in the
// library for each year, computed for New Delhi (IST) from the panchang
// rules in rules.mjs. Run from the repo root:
//
//   node scripts/festival-dates/generate.mjs 2026 2030
//
// To add a year, change the range, run it, check the new dates against
// published panchangs (see README.md) and add any close calls to OVERRIDES.
import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
// The app's panchang engine is plain JS in a CommonJS package; copy it as an
// ES module so this script uses exactly the same calculations.
fs.copyFileSync(path.join(here, "../../lib/panchang.js"), path.join(here, "panchang.generated.mjs"));
const { rules } = await import(pathToFileURL(path.join(here, "rules.mjs")).href);

const [from = 2026, to = 2030] = process.argv.slice(2).map(Number);

// Published dates that differ from the rules, each with its reason.
// [festival, year, name] -> "M-D"
const OVERRIDES = [
  // Holi 2026: the 3 March lunar eclipse (and its sutak) moved Holika Dahan to
  // 3 March in most published panchangs; Holi was 4 March.
  ["holi", 2026, "holika", "3-3"], ["holi", 2026, "holi", "3-4"], ["holi", 2026, "holaStart", "3-4"], ["holi", 2026, "holaEnd", "3-6"],
  // Cheti Chand 2026 as published in the app's original research.
  ["newyear", 2026, "chetichand", "3-19"],
  // Hartalika 2026 fell on Ganesh Chaturthi; many observed it on 13 Sep.
  ["teej", 2026, "hartalikaEve", "9-13"],
  // Hartalika 2029: Tritiya touches sunrise on 11 Sep by about 5 minutes,
  // within the spread between panchangs; Dekho Panchang and Hindupad give 10 Sep.
  ["teej", 2029, "hartalika", "9-10"],
];

const md = (o) => `${o.m + 1}-${o.d}`;
const out = {};
for (let Y = from; Y <= to; Y++) {
  const r = rules(Y);
  for (const [fest, named] of Object.entries(r)) {
    out[fest] ||= {};
    out[fest][Y] = {};
    for (const [k, v] of Object.entries(named)) {
      if (v instanceof Date) continue; // sankranti moments are only used to derive dates
      out[fest][Y][k] = md(v);
    }
  }
}
for (const [fest, Y, k, v] of OVERRIDES) if (out[fest]?.[Y]) out[fest][Y][k] = v;
// Bhai Dooj is its own festival in the library, on Diwali's last day.
out.bhaidooj = Object.fromEntries(Object.entries(out.diwali).map(([Y, d]) => [Y, { bhaidooj: d.bhaidooj }]));

const body = `// Generated by scripts/festival-dates/generate.mjs — do not edit by hand.
// Festival days for New Delhi (IST) as "M-D" (month 1–12), ${from}–${to}.
// Rules, sources and the overrides used are in scripts/festival-dates/.
export const FIRST_YEAR = ${from};
export const LAST_YEAR = ${to};
export const FESTIVAL_DATES = ${JSON.stringify(out, null, 1).replace(/\n\s*/g, " ")};
`;
fs.writeFileSync(path.join(here, "../../lib/festivalDates.js"), body);
console.log(`lib/festivalDates.js: ${Object.keys(out).length} festivals, ${from}–${to}`);
